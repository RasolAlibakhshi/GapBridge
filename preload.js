const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  state: () => ipcRenderer.invoke('state'),
  addRoot: () => ipcRenderer.invoke('addRoot'),
  removeRoot: p => ipcRenderer.invoke('removeRoot', p),
  copyInstructions: () => ipcRenderer.invoke('copyInstructions'),
  copyToken: () => ipcRenderer.invoke('copyToken'),
  killAll: () => ipcRenderer.invoke('killAll'),
  rotateToken: () => ipcRenderer.invoke('rotateToken'),
  openData: () => ipcRenderer.invoke('openData'),
  setAuto: on => ipcRenderer.invoke('setAuto', on),
  shellMenu: on => ipcRenderer.invoke('shellMenu', on),
  jobs: () => ipcRenderer.invoke('jobs'),
  jobKill: id => ipcRenderer.invoke('jobKill', id),
  setHotkeys: h => ipcRenderer.invoke('setHotkeys', h),
  terminalStart: opts => ipcRenderer.invoke('terminalStart', opts),
  terminalWrite: data => ipcRenderer.invoke('terminalWrite', data),
  terminalResize: (cols, rows) => ipcRenderer.invoke('terminalResize', cols, rows),
  terminalStop: () => ipcRenderer.invoke('terminalStop'),
  terminalView: () => ipcRenderer.invoke('terminalView'),
  terminalSetAgent: on => ipcRenderer.invoke('terminalSetAgent', on),
  onTermStarted: cb => ipcRenderer.on('term-started', (_, v) => cb(v)),
  onTermData: cb => ipcRenderer.on('term-data', (_, t) => cb(t)),
  onTermExit: cb => ipcRenderer.on('term-exit', (_, c) => cb(c)),
  browserInfo: () => ipcRenderer.invoke('browserInfo'),
  browserSet: o => ipcRenderer.invoke('browserSet', o),
  browserPick: () => ipcRenderer.invoke('browserPick'),
  browserLaunch: () => ipcRenderer.invoke('browserLaunch'),
  browserStop: () => ipcRenderer.invoke('browserStop'),
  browserResetProfile: () => ipcRenderer.invoke('browserResetProfile'),
  perms: () => ipcRenderer.invoke('perms'),
  setPerm: (g, m) => ipcRenderer.invoke('setPerm', g, m),
  historyList: n => ipcRenderer.invoke('historyList', n),
  historyRestore: id => ipcRenderer.invoke('historyRestore', id),
  auditTail: o => ipcRenderer.invoke('auditTail', o),
  onboardDone: done => ipcRenderer.invoke('onboardDone', done),
  openExtensionDir: () => ipcRenderer.invoke('openExtensionDir'),
  updateInfo: () => ipcRenderer.invoke('updateInfo'),
  updateSet: o => ipcRenderer.invoke('updateSet', o),
  updateCheck: () => ipcRenderer.invoke('updateCheck'),
  onUpdate: cb => ipcRenderer.on('update-status', (_, s) => cb(s)),
  onHistoryChanged: cb => ipcRenderer.on('history-changed', () => cb()),
  logList: o => ipcRenderer.invoke('logList', o),
  logClear: () => ipcRenderer.invoke('logClear'),
  logCopy: o => ipcRenderer.invoke('logCopy', o),
  onLog: cb => ipcRenderer.on('log', (_, l) => cb(l)),
  onStatus: cb => ipcRenderer.on('status', (_, s) => cb(s)),
});
